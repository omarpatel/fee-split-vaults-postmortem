import { describe, expect, it } from 'vitest'
import { DISCLOSURE, REFUSAL_CLASSES, type RefusalClass } from '../../../../config/protocol.js'
import { classifyContent } from '../classify.js'
import {
  composeDisclosedMessage,
  disclosureTokens,
  renderDisclosure,
  stripAuthoredDisclosure,
  verifyDisclosurePresent,
  type DisclosureSpec,
} from '../disclosure.js'
import { buildLinkPolicy, checkLinksAndAddresses, checkUrl } from '../links.js'
import { REFUSAL_RULES, scanForRefusals, scanForRefusalsWith } from '../refusal.js'
import { countCodePoints, normalizeVisibleText, truncateToBudget } from '../text.js'
import { checkTickerPolicy, extractCashtags } from '../tickers.js'
import type { AccountBinding } from '../types.js'

const SPEC: DisclosureSpec = {
  operatorName: 'Venue Desk',
  receiptUrl: 'https://receipts.example.com/0x1111111111111111111111111111111111111111',
  paidPromotion: true,
}

describe('canonical disclosure', () => {
  it('carries all four elements in the visible body', () => {
    const rendered = renderDisclosure(SPEC)
    expect(rendered.startsWith(DISCLOSURE.paidPromotionTag)).toBe(true)
    expect(rendered).toContain(DISCLOSURE.aiOperationTag)
    expect(rendered).toContain(SPEC.operatorName)
    expect(rendered).toContain(SPEC.receiptUrl)
    expect(disclosureTokens(SPEC)).toHaveLength(4)
  })

  it('drops the paid tag for operational content but keeps bot identification', () => {
    const rendered = renderDisclosure({ ...SPEC, paidPromotion: false })
    expect(rendered).not.toContain(DISCLOSURE.paidPromotionTag)
    expect(rendered).toContain(DISCLOSURE.aiOperationTag)
  })
})

describe('truncation', () => {
  it('eats the body and leaves the disclosure whole', () => {
    const body = 'operational detail '.repeat(60)
    const composed = composeDisclosedMessage({
      body,
      spec: SPEC,
      measure: countCodePoints,
      maxChars: 280,
    })

    expect(composed.ok).toBe(true)
    if (!composed.ok) return
    expect(countCodePoints(composed.text)).toBeLessThanOrEqual(280)
    expect(composed.text.endsWith(renderDisclosure(SPEC))).toBe(true)
    expect(composed.bodyTruncated).toBe(true)
    expect(verifyDisclosurePresent(composed.text, SPEC).ok).toBe(true)
  })

  it('publishes the disclosure alone rather than a body without it', () => {
    const composed = composeDisclosedMessage({
      body: 'a body that has no room',
      spec: SPEC,
      measure: countCodePoints,
      maxChars: countCodePoints(renderDisclosure(SPEC)) + 1,
    })

    expect(composed.ok).toBe(true)
    if (!composed.ok) return
    expect(composed.text).toBe(renderDisclosure(SPEC))
  })

  it('refuses when the disclosure itself does not fit', () => {
    const composed = composeDisclosedMessage({
      body: 'anything',
      spec: SPEC,
      measure: countCodePoints,
      maxChars: 10,
    })

    expect(composed.ok).toBe(false)
    if (composed.ok) return
    expect(composed.rejection.reason).toBe('disclosure_exceeds_channel_limit')
  })

  it('never leaves a half-truncated URL pointing somewhere else', () => {
    const outcome = truncateToBudget(
      'read more at https://receipts.example.com/very/long/path',
      countCodePoints,
      30,
    )
    expect(outcome.truncated).toBe(true)
    expect(outcome.text).not.toContain('https://')
  })
})

describe('stripping model-authored disclosure', () => {
  it('removes tags, claims, forged receipt lines and the operator name', () => {
    const outcome = stripAuthoredDisclosure(
      '#ad #sponsored AI-generated by Venue Desk. Disclosure: paid partnership. ' +
        'receipts: https://evil.example/x. The pinned message is current. NFA, DYOR.',
      'Venue Desk',
    )

    expect(outcome.body).toContain('The pinned message is current')
    expect(outcome.removed).toContain('#ad')
    expect(outcome.removed).toContain('#sponsored')
    expect(outcome.body).not.toContain('#ad')
    expect(outcome.body).not.toContain('evil.example')
    expect(outcome.body).not.toContain('Venue Desk')
    expect(outcome.body).not.toMatch(/nfa|dyor|paid partnership/i)
  })

  it('sees through full-width homoglyphs and zero-width padding', () => {
    const raw = '\uFF03\uFF41d AI\u200B-operated. Operational note.'
    const outcome = stripAuthoredDisclosure(normalizeVisibleText(raw), 'Venue Desk')
    expect(outcome.body).toBe('Operational note.')
  })
})

describe('refusal classifier', () => {
  it('refuses advice, prediction and comparative merit', () => {
    expect(scanForRefusals('Buy now, this goes 100x').refused).toBe(true)
    expect(scanForRefusals('price target is $2 by friday').refused).toBe(true)
    expect(scanForRefusals('a better investment than $OTHER').refused).toBe(true)
    expect(scanForRefusals('wen moon ser').refused).toBe(true)
    expect(scanForRefusals('put your savings in early').refused).toBe(true)
  })

  it('permits operational facts', () => {
    expect(scanForRefusals('How to buy is in the pinned message.').refused).toBe(false)
    expect(scanForRefusals('The buy/sell tax is unchanged at 0 bps.').refused).toBe(false)
    expect(scanForRefusals('Buyback is enabled on this token, so the creator net halves.').refused).toBe(
      false,
    )
  })

  it('covers every class in the protocol config', () => {
    for (const cls of REFUSAL_CLASSES) {
      expect(REFUSAL_RULES[cls].length).toBeGreaterThan(0)
    }
  })

  it('fails closed when a class has no matcher', () => {
    const drifted = scanForRefusalsWith('an entirely innocuous operational note', REFUSAL_RULES, [
      ...REFUSAL_CLASSES,
      'unreviewed_new_class' as unknown as RefusalClass,
    ])
    expect(drifted.refused).toBe(true)
    expect(drifted.reason).toContain('unmapped_refusal_class')
  })
})

describe('link and address policy', () => {
  const policy = buildLinkPolicy({
    allowedHosts: ['vnx.example'],
    allowedAddresses: ['0x2222222222222222222222222222222222222222'],
  })

  it('rejects userinfo, ports, ip literals, punycode and plain http', () => {
    expect(checkUrl('https://vnx.example@evil.tld/x', policy)?.reason).toBe(
      'link_carries_credentials',
    )
    expect(checkUrl('https://evil.tld/x', policy)?.reason).toBe('host_not_allowlisted')
    expect(checkUrl('https://vnx.example:8443/x', policy)?.reason).toBe('link_has_explicit_port')
    expect(checkUrl('https://203.0.113.9/x', policy)?.reason).toBe('link_to_ip_literal')
    expect(checkUrl('https://pönsx.example/x', policy)?.reason).toBe('punycode_host')
    expect(checkUrl('https://xn--!!!.example/x', policy)?.reason).toBe('unparseable_link')
    expect(checkUrl('http://vnx.example/x', policy)?.reason).toBe('insecure_link_scheme')
    expect(checkUrl('https://docs.vnx.example/x', policy)).toBeNull()
  })

  it('hard-rejects any address that is not allowlisted', () => {
    const rejection = checkLinksAndAddresses(
      'new contract 0x651c06a1a38c5727f0d3ef7420d90e02e0fee33d',
      [],
      policy,
    )
    expect(rejection?.reason).toBe('unallowlisted_address_in_body')
  })

  it('rejects dot-obfuscated domains', () => {
    expect(checkLinksAndAddresses('go to claim dot example now', [], policy)?.reason).toBe(
      'obfuscated_link',
    )
  })

  it('catches an address broken up with zero-width characters', () => {
    const rejection = checkLinksAndAddresses(
      'send to 0xdeadbeef\u200Bdeadbeefdeadbeefdeadbeefdeadbeef',
      [],
      policy,
    )
    expect(rejection?.reason).toBe('unallowlisted_address_in_body')
  })
})

describe('ticker policy', () => {
  const binding: AccountBinding = {
    accountId: 'x-op-1',
    channel: 'x_operator',
    coinRef: 'vnx',
    vault: '0x1111111111111111111111111111111111111111',
    token: '0x2222222222222222222222222222222222222222',
    ticker: 'VNX',
    delegated: false,
  }
  const roster = [
    { vault: binding.vault, token: binding.token, ticker: 'VNX' },
    {
      vault: '0x3333333333333333333333333333333333333333',
      token: '0x4444444444444444444444444444444444444444',
      ticker: 'RIVAL',
    },
  ]

  it('extracts cashtags case-insensitively', () => {
    expect(extractCashtags('$vnx and $Rival')).toEqual(['VNX', 'RIVAL'])
  })

  it('accepts the bound ticker alone', () => {
    expect(checkTickerPolicy({ text: '$VNX desk update', binding, roster })).toBeNull()
  })

  it('refuses a second ticker and refuses another client by name', () => {
    expect(
      checkTickerPolicy({ text: '$VNX and $RIVAL both moved', binding, roster })?.reason,
    ).toBe('ticker_limit_exceeded')
    expect(checkTickerPolicy({ text: 'RIVAL had a good week', binding, roster })?.reason).toBe(
      'cross_promotion',
    )
  })
})

describe('content classification', () => {
  it('is a rule engine that fails closed to promotional', () => {
    expect(classifyContent({ body: 'join the giveaway' }).isPromotional).toBe(true)
    expect(classifyContent({ body: 'we are aware of the outage' }).isPromotional).toBe(false)
    expect(classifyContent({ body: 'the contract address is pinned' }).isPromotional).toBe(false)

    const ambiguous = classifyContent({ body: 'a sentence with no signal either way' })
    expect(ambiguous.isPromotional).toBe(true)
    expect(ambiguous.defaultedToPromotional).toBe(true)
  })

  it('never lets a declared false downgrade a rule hit', () => {
    const classified = classifyContent({
      body: 'join the giveaway and follow for more',
      declaredPromotional: false,
    })
    expect(classified.isPromotional).toBe(true)
    expect(classified.matched).toContain('promo.call_to_action')
  })

  it('treats any creative asset as promotional', () => {
    expect(classifyContent({ body: 'status update', hasImages: true }).isPromotional).toBe(true)
  })
})
